// Транслитерация ФИО → логин (дизайн-правки этого раунда).
// Кириллица → латиница (полная карта а-я/ё), нижний регистр, слова через '-',
// только [a-z0-9-], повторные '-' схлопываются, по краям обрезаются. Пустой ввод → ''.
// При коллизии логина суффикс добавляет вызывающий код (бек вернул 409).

const MAP: Record<string, string> = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh',
  з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o',
  п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'shch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu',
  я: 'ya',
};

export function translitLogin(fio: string): string {
  const lower = fio.toLowerCase();

  let out = '';
  for (const ch of lower) {
    if (Object.prototype.hasOwnProperty.call(MAP, ch)) {
      out += MAP[ch];
    } else if (/[a-z0-9]/.test(ch)) {
      out += ch;
    } else {
      // Любой иной символ (пробел, пунктуация, неизвестная буква) → разделитель.
      out += '-';
    }
  }

  return out
    .replace(/[^a-z0-9-]/g, '') // подстраховка: только разрешённый набор
    .replace(/-+/g, '-') // схлопнуть повторы '-'
    .replace(/^-+|-+$/g, ''); // обрезать по краям
}
